#!/usr/bin/env bash
set -eu -o pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

usage() {
  cat >&2 <<USAGE
usage: $0 [--output <directory>] [ipswrun flags] <release>
       $0 [--output <directory>] [ipswrun flags] --all

<release>  what ipswrun accepts: a build (24G90), a version, the https URL of a restore image,
           or several separated by commas
--all      every source_type "ipsw" release in loctables/sources.json that has no dump yet
--output   where the .sql files go (default: this directory)
ipswrun flags passed on: --cache <directory>, --stream-compressed (macOS 13 and 14), --trace
USAGE
}
bad_usage() { usage; exit 1; }

releases=""
all=0
output_dir="$script_dir"
pass=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --output) [[ $# -ge 2 && -n "$2" ]] || bad_usage; output_dir="$2"; shift 2 ;;
    --cache) [[ $# -ge 2 && -n "$2" ]] || bad_usage; pass+=("$1" "$2"); shift 2 ;;
    --all) all=1; shift ;;
    --stream-compressed|--trace) pass+=("$1"); shift ;;
    --help|-h) usage; exit 0 ;;
    -*) bad_usage ;;
    *) [[ -z "$releases" ]] || bad_usage; releases="$1"; shift ;;
  esac
done
if [[ "$all" -eq 1 && -n "$releases" ]] || [[ "$all" -eq 0 && -z "$releases" ]]; then bad_usage; fi

if [[ "$all" -eq 1 ]]; then
  releases="$(/usr/bin/python3 -I -c '
import json, os, sys
print(",".join(r["url"] for r in json.load(open(sys.argv[1]))["releases"] if r["source_type"] == "ipsw"
               and not os.path.exists(os.path.join(sys.argv[2], "%s-%s.sql" % (r["version"], r["build"])))))' \
    "$script_dir/../loctables/sources.json" "$output_dir")"
  if [[ -z "$releases" ]]; then echo "every release already has a dump" >&2; exit 0; fi
fi

ipswrun="${IPSWRUN_BIN:-ipswrun}"
for tool in "$ipswrun" clang; do
  if ! command -v "$tool" >/dev/null 2>&1; then echo "$tool is required; see schemas/readme.md" >&2; exit 1; fi
done
sqlite3=/usr/bin/sqlite3

work="$(mktemp -d "${TMPDIR:-/tmp}/chatdb-schema.XXXXXX")"
trap 'rm -rf "$work"' EXIT

# Old enough for every release's dyld: classic fixups, macOS 11 deployment target.
clang -arch arm64 -mmacosx-version-min=11.0 -O1 -Wl,-no_fixup_chains -framework CoreFoundation \
  "$script_dir/runner.c" -o "$work/runner"

# Two independent runs per release, each in a fresh home.
failed=0
for n in 1 2; do
  "$ipswrun" --home "$work/$n/{build}" --report "$work/$n/{build}.json" ${pass[@]+"${pass[@]}"} \
    "$releases" "$work/runner" </dev/null || failed=1
done

from_objects="FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\'
              ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'trigger' THEN 2 ELSE 3 END, name"

dump() {
  local build="$1" n db version client_version user_version out
  for n in 1 2; do
    if [[ "$(/usr/bin/plutil -extract exit_code raw "$work/$n/$build.json" 2>/dev/null)" != 0 ]]; then
      echo "$build: run $n did not create the database" >&2; return 1
    fi
    "$sqlite3" "$work/$n/$build/Library/Messages/chat.db" "SELECT type, name, hex(sql) $from_objects" >"$work/$n/$build.objects"
  done
  if [[ ! -s "$work/1/$build.objects" ]]; then echo "$build: the initializer created no schema" >&2; return 1; fi
  # Creation order may differ between runs, the objects may not.
  if ! cmp -s "$work/1/$build.objects" "$work/2/$build.objects"; then
    echo "$build: two runs disagree:" >&2
    diff "$work/1/$build.objects" "$work/2/$build.objects" | cut -c1-200 >&2 || true
    return 1
  fi

  db="$work/1/$build/Library/Messages/chat.db"
  version="$(/usr/bin/plutil -extract version raw "$work/1/$build.json")"
  client_version="$("$sqlite3" "$db" "SELECT value FROM _SqliteDatabaseProperties WHERE key = '_ClientVersion'")"
  user_version="$("$sqlite3" "$db" "PRAGMA user_version")"

  # sqlite3's own .schema text for the objects recreated in a stable order.
  "$sqlite3" "$db" "SELECT sql || ';' $from_objects" | "$sqlite3" "$work/$build.db"
  out="$output_dir/$version-$build.sql"
  {
    echo "-- chat.db schema created by IMDPersistence on macOS $version ($build)"
    echo "-- _ClientVersion ${client_version:-None}, user_version $user_version. Generated by schemas/dump.sh; do not edit."
    "$sqlite3" "$work/$build.db" '.schema --indent --nosys'
  } > "$out.tmp"
  mv "$out.tmp" "$out"
  echo "$out: $(wc -l < "$work/1/$build.objects" | tr -d ' ') objects" >&2
}

mkdir -p "$output_dir"
shopt -s nullglob
for report in "$work"/1/*.json; do
  dump "$(basename "$report" .json)" || failed=1
done
exit "$failed"
